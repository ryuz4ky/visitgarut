const assert=require('node:assert/strict'),fs=require('node:fs')
const {PGlite}=require('@electric-sql/pglite')
const {relatedPlaceSuggestionsSql:sql}=require('../.related-places-test/related-places.js')
;(async()=>{
 const db=new PGlite()
 try{
  await db.exec(fs.readFileSync('db/001-mvp.sql','utf8'))
  const add=async(id,name,category='wisata',district='Leles',lat=null,lng=null,status='published')=>db.query('INSERT INTO vg_places(id,slug,name,category,district,latitude,longitude,status) VALUES($1,$2,$3,$4,$5,$6,$7,$8)',[id,`place-${id}`,name,category,district,lat,lng,status])
  const ids=async(id)=>(await db.query(sql,[id])).rows.map(x=>x.id)
  await add(1,'Origin','wisata',' Leles ',-7,107)
  await add(2,'Z same district near','wisata','leles',-7.01,107)
  await add(3,'A same district far','wisata','Leles',-7.9,107)
  await add(4,'Closest outside district','wisata','Garut Kota',-7.001,107)
  await add(5,'Draft same district','wisata','Leles',-7,107,'draft')
  await add(6,'Different category','hotel','Leles',-7,107)
  assert.deepEqual(await ids(1),[2,3,4],'same district precedes outside district, then proximity; no draft, origin, or other category')
  await db.query("UPDATE vg_places SET status='draft' WHERE id=2")
  assert.deepEqual(await ids(1),[3,4],'withdrawn suggestions disappear immediately')
  assert.deepEqual(await ids(2),[],'withdrawn origin has no recommendations')
  assert.deepEqual(await ids(999999),[])
  await db.exec('TRUNCATE vg_places CASCADE')
  await add(1,'Origin','wisata','',-7,107)
  await db.exec("INSERT INTO vg_places(id,slug,name,category,district,latitude,longitude,status) SELECT n,'many-'||n,'A '||n,'wisata','',-8,107,'published' FROM generate_series(10,120) n")
  await add(1001,'Z nearest beyond old cap','wisata','',-7.0001,107)
  assert.equal((await ids(1))[0],1001,'nearby result beyond first 100 names is eligible')
  await db.exec('TRUNCATE vg_places CASCADE')
  await add(1,'Origin','cafe','Garut')
  await add(2,'B no point','cafe','Garut')
  await add(3,'A with point','cafe','Garut',-7,107)
  await add(4,'C no point','cafe','Garut')
  assert.deepEqual(await ids(1),[3,2,4],'missing origin coordinates use stable alphabetical fallback')
  await db.query('UPDATE vg_places SET latitude=-7,longitude=107 WHERE id=1')
  // Simulate legacy data imported before the current coordinate constraint.
  await db.exec('ALTER TABLE vg_places DROP CONSTRAINT vg_places_latitude_check')
  await db.query('UPDATE vg_places SET latitude=91,longitude=107 WHERE id=2')
  assert.deepEqual(await ids(1),[3,2,4],'invalid coordinates never outrank usable coordinates')
  await db.query('UPDATE vg_places SET latitude=-7.01,longitude=NULL WHERE id=4')
  assert.deepEqual(await ids(1),[3,2,4],'partial coordinate pair uses fallback')
  console.log('PASS related places: public origin/candidates, category/exclusion, normalized district, proximity, withdrawal, >100 records, missing/invalid coordinates and stable fallback')
 }finally{await db.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
